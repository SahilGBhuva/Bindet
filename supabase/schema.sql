-- bindit schema for Supabase Postgres.
-- Reference only: the backend creates these tables on first start, then
-- supabase/migrations are applied in filename order (see supabase/README.md).

create table if not exists student_progress (
  student_id text primary key,
  total_xp integer not null default 0,
  attempts integer not null default 0,
  correct_answers integer not null default 0,
  streak integer not null default 0,
  best_streak integer not null default 0,
  last_active_date date,
  login_streak integer not null default 0,
  best_login_streak integer not null default 0,
  last_login_date date,
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists topic_progress (
  student_id text not null references student_progress(student_id) on delete cascade,
  topic text not null,
  attempts integer not null default 0,
  correct_answers integer not null default 0,
  primary key (student_id, topic)
);

create table if not exists profiles (
  student_id text primary key references student_progress(student_id) on delete cascade,
  username varchar(24) not null unique,
  display_name varchar(40) not null,
  avatar_path varchar(500) not null default '',
  friend_code varchar(12) not null unique,
  daily_goal integer not null default 20,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists generated_questions (
  question_id varchar(64) primary key,
  student_id varchar(100) not null,
  question varchar(500) not null,
  correct_answer varchar(200) not null,
  topic varchar(50) not null,
  difficulty integer not null,
  completed integer not null default 0,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists friendships (
  id integer generated by default as identity primary key,
  requester_id varchar(100) not null references profiles(student_id) on delete cascade,
  recipient_id varchar(100) not null references profiles(student_id) on delete cascade,
  status varchar(10) not null default 'pending',
  created_at timestamptz not null default timezone('utc', now()),
  constraint uq_friend_request_direction unique (requester_id, recipient_id)
);

create table if not exists friend_quests (
  id integer generated by default as identity primary key,
  creator_id varchar(100) not null references profiles(student_id) on delete cascade,
  partner_id varchar(100) not null references profiles(student_id) on delete cascade,
  target_xp integer not null default 100 check (target_xp between 50 and 1000),
  starting_xp integer not null default 0,
  status varchar(12) not null default 'active',
  created_at timestamptz not null default timezone('utc', now()),
  expires_at timestamptz not null
);

create table if not exists uploaded_images (
  id uuid primary key,
  owner_id text not null,
  storage_path text not null unique,
  original_name varchar(255) not null,
  content_type varchar(100) not null,
  size_bytes integer not null check (size_bytes > 0 and size_bytes <= 5242880),
  created_at timestamptz not null default timezone('utc', now())
);

-- Same column types as backend/note_store.py. student_id holds a Supabase user
-- id or a guest id, so it is not a foreign key to auth.users.
create table if not exists study_notes (
  id varchar(36) primary key,
  student_id varchar(100) not null,
  course varchar(120) not null,
  unit varchar(160) not null,
  file_name varchar(255) not null,
  content_type varchar(100) not null default '',
  text text not null,
  size_bytes integer not null check (size_bytes between 1 and 10485760),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists progress_claims (
  guest_id text primary key,
  account_id text not null,
  claimed_at timestamptz not null default timezone('utc', now())
);

create index if not exists progress_claims_account_id_idx on progress_claims (account_id);
create index if not exists topic_progress_student_id_idx on topic_progress (student_id);
create index if not exists generated_questions_student_id_idx on generated_questions (student_id);
create index if not exists uploaded_images_owner_id_idx on uploaded_images (owner_id, created_at desc);
create index if not exists study_notes_student_unit_idx on study_notes (student_id, course, unit, created_at desc);
create index if not exists profiles_username_idx on profiles (username);

alter table student_progress enable row level security;
alter table topic_progress enable row level security;
alter table profiles enable row level security;
alter table generated_questions enable row level security;
alter table friendships enable row level security;
alter table friend_quests enable row level security;
alter table uploaded_images enable row level security;
alter table study_notes enable row level security;

drop policy if exists "Students own study notes" on study_notes;
-- Read-only for the owner; notes are written only by the backend (see 20261003_security_hardening.sql).
create policy "Students own study notes" on study_notes
  for select to authenticated using (auth.uid()::text = student_id::text);
alter table progress_claims enable row level security;

